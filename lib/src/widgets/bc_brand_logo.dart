/// Identity providers with a bundled brand mark.
///
/// Used by [BCBrandLogo] and [BCSocialAuthButton] — no image assets and no
/// SVG package needed, the marks are vector path data painted at any size.
enum BCSocialProvider {
  google,
  apple,
  github,
  facebook,
  microsoft,
  x,
  discord,
  slack,
  notion,
  linear;

  /// The provider's display name, e.g. `GitHub`.
  String get label => _brandMarks[this]!.label;

  /// Whether the official mark is a single-colour glyph (Apple, GitHub, X,
  /// Notion, Linear). Those are painted in the surrounding text colour so
  /// they stay legible in both themes.
  bool get hasMonochromeMark => _brandMarks[this]!.colorPaths.isEmpty;
}

