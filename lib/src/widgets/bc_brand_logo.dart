/// Parsed paths are shared across every logo instance — parsing is done once
/// per distinct path string, at first paint.
final Map<String, Path> _pathCache = {};

Path _parsedPath(String data) =>
    _pathCache[data] ??= parseSvgPathData(data);

/// A provider's brand mark, painted as vector art at [size].
class BCBrandLogo extends StatelessWidget {
  const BCBrandLogo({
    super.key,
    required this.provider,
    this.size = 20,
    this.color,
  });

  final BCSocialProvider provider;

  /// Side of the square the mark is fitted into, preserving its aspect ratio.
  final double size;

  /// Paints the mark as a single-colour glyph.
  ///
  /// When null the official brand colours are used; providers whose mark is
  /// monochrome by design ([BCSocialProvider.hasMonochromeMark]) fall back to
  /// the theme foreground so they stay legible in dark mode.
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final mark = _brandMarks[provider]!;
    final resolved =
        color ?? (mark.colorPaths.isEmpty ? context.bcTheme.foreground : null);

    return SizedBox.square(
      dimension: size,
      child: CustomPaint(
        painter: _BrandMarkPainter(mark: mark, color: resolved),
        isComplex: true,
        willChange: false,
      ),
    );
  }
}

class _BrandMarkPainter extends CustomPainter {
  const _BrandMarkPainter({required this.mark, required this.color});

  final _BrandMark mark;

  /// Null paints the colour layers; non-null paints the monochrome glyph.
  final Color? color;

  @override
  void paint(Canvas canvas, Size size) {
    final tint = color;
    final viewBox = tint != null ? mark.monoSize : mark.colorSize;
    final scale = math.min(
      size.width / viewBox.width,
      size.height / viewBox.height,
    );

    canvas.save();
    canvas.translate(
      (size.width - viewBox.width * scale) / 2,
      (size.height - viewBox.height * scale) / 2,
    );
    canvas.scale(scale);

    if (tint != null) {
      canvas.drawPath(_parsedPath(mark.monoPath), Paint()..color = tint);
    } else {
      for (final (fill, data) in mark.colorPaths) {
        canvas.drawPath(_parsedPath(data), Paint()..color = fill);
      }
    }

    canvas.restore();
  }

  @override
  bool shouldRepaint(_BrandMarkPainter oldDelegate) =>
      oldDelegate.mark != mark || oldDelegate.color != color;
}
